"""Export the weekly-pack decision rules as test cases for the web (Frontend plan F0, §10.2).

Each case is a decision body run through the API's own request model (`routers/packs.DecisionIn`, which applies the
graph's `ApprovalDecision` rules D1 and the caps): the web's client-side checks are tested on the same cases, so the
two sides cannot drift. No database, no network.

    uv run python tools/export_approval_cases.py            write web/tests/fixtures/approval_cases.json
    uv run python tools/export_approval_cases.py --check    exit 1 when the file differs from the rules (the CI)
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pydantic import ValidationError  # noqa: E402

from pipelines.agents.deck import charts  # noqa: E402
from pipelines.agents.graphs import models as gm  # noqa: E402
from pipelines.api.routers.packs import DecisionIn  # noqa: E402

FILE = ROOT / "web" / "tests" / "fixtures" / "approval_cases.json"
TREND_WEEK = list(charts.TREND_WEEKS)[0]
MEASURE = list(charts.VARIANCE_MEASURES)[0]
TREND = {"chart": "trend", "weeks": TREND_WEEK}
VARIANCE = {"chart": "variance", "measure": MEASURE}

CASES: list[tuple[str, dict]] = [
    ("approve alone", {"decision": "approve"}),
    ("approve with a comment", {"decision": "approve", "comment": "Good week."}),
    ("approve carrying an edit", {"decision": "approve", "edits": [{"bullet": 0, "text": "New text."}]}),
    ("reject alone", {"decision": "reject", "comment": "Wrong week."}),
    ("reject carrying a chart change", {"decision": "reject", "charts": [TREND]}),
    ("edit with a text edit", {"decision": "edit", "edits": [{"bullet": 1, "text": "Clearer wording."}]}),
    ("edit with an addition", {"decision": "edit", "additions": [{"slide": 3, "text": "Ask the top client."}]}),
    ("edit with a chart change only", {"decision": "edit", "charts": [TREND]}),
    ("edit with nothing", {"decision": "edit"}),
    ("edit carrying a steer", {"decision": "edit", "edits": [{"bullet": 0, "text": "x"}], "steer": "More cash."}),
    ("revise with a steer", {"decision": "revise", "steer": "Focus on collections."}),
    ("revise with an analysis edit", {"decision": "revise", "analysis_edits": [
        {"target": "caveat", "op": "add", "text": "Week 53 is not in this year."}]}),
    ("revise carrying a text edit", {"decision": "revise", "steer": "x", "edits": [{"bullet": 0, "text": "y"}]}),
    ("revise with nothing", {"decision": "revise"}),
    ("two changes to one chart", {"decision": "edit", "charts": [TREND, {**TREND}]}),
    ("too many chart changes", {"decision": "edit", "charts": [TREND, VARIANCE] + [TREND] * gm.MAX_CHART_CHANGES}),
    ("steer too long", {"decision": "revise", "steer": "x" * (gm.MAX_STEER_CHARS + 1)}),
    ("addition too long", {"decision": "edit", "additions": [{"slide": 3, "text": "x" * (gm.MAX_ADDITION_CHARS + 1)}]}),
    ("analysis replace without an index", {"decision": "revise", "analysis_edits": [
        {"target": "summary", "op": "replace", "text": "x"}]}),
    ("a summary point cannot be removed", {"decision": "revise", "analysis_edits": [
        {"target": "summary", "op": "remove", "index": 0}]}),
    ("a chart option the chart does not have", {"decision": "edit", "charts": [{"chart": "trend", "measure": MEASURE}]}),
    ("unknown field (an employee id)", {"decision": "approve", "approver_employee_id": 13}),
]


def build() -> str:
    out = []
    for name, body in CASES:
        try:
            DecisionIn.model_validate(body)
            out.append({"name": name, "body": body, "valid": True})
        except ValidationError as exc:
            first = exc.errors()[0]
            out.append({"name": name, "body": body, "valid": False,
                        "error": str(first.get("msg", "")).removeprefix("Value error, ")})
    return json.dumps({"_note": "GENERATED by tools/export_approval_cases.py from the API's DecisionIn — do not edit.",
                       "limits": {"max_chart_changes": gm.MAX_CHART_CHANGES, "max_analysis_edits": gm.MAX_ANALYSIS_EDITS,
                                  "max_steer_chars": gm.MAX_STEER_CHARS, "max_addition_chars": gm.MAX_ADDITION_CHARS},
                       "cases": out}, ensure_ascii=False, indent=2) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build()
    if args.check:
        same = FILE.exists() and FILE.read_text(encoding="utf-8") == text
        print("✅ approval cases match the API's rules" if same else "❌ approval cases differ: run the tool")
        sys.exit(0 if same else 1)
    FILE.write_bytes(text.encode("utf-8"))
    n = json.loads(text)["cases"]
    print(f"✅ {len(n)} approval cases written ({sum(c['valid'] for c in n)} valid) → {FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
