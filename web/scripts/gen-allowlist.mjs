// Builds src/lib/bff/allowlist.generated.ts from the API's OpenAPI snapshot (docs/api/openapi.json, ADR-064 P7).
// The BFF proxies only these (method, path template) pairs; anything else is a 404 without calling the API.
// /auth/login and /auth/logout are not proxied: /bff/login and /bff/logout own the session cookie.
import { readFileSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync(new URL("../../docs/api/openapi.json", import.meta.url), "utf8"));
const PREFIX = "/api/v1";
const NOT_PROXIED = new Set(["/auth/login", "/auth/logout"]);
const rows = [];
for (const [path, item] of Object.entries(spec.paths)) {
  if (!path.startsWith(PREFIX + "/")) throw new Error(`unexpected path outside ${PREFIX}: ${path}`);
  const template = path.slice(PREFIX.length);
  if (NOT_PROXIED.has(template)) continue;
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    if (item[method]) rows.push({ method: method.toUpperCase(), template });
  }
}
rows.sort((a, b) => a.template.localeCompare(b.template) || a.method.localeCompare(b.method));
const body = rows.map((r) => `  { method: "${r.method}", template: "${r.template}" },`).join("\n");
const out = `// GENERATED by scripts/gen-allowlist.mjs from docs/api/openapi.json — do not edit by hand.
export const ALLOWED_ROUTES: ReadonlyArray<{ method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE"; template: string }> = [
${body}
];
`;
writeFileSync(new URL("../src/lib/bff/allowlist.generated.ts", import.meta.url), out, "utf8");
console.log(`✅ allow-list: ${rows.length} routes from ${Object.keys(spec.paths).length} OpenAPI paths`);
